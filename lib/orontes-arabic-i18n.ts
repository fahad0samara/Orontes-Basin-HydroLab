export function translateLandformAr(landform: string): string {
  if (landform.includes('Jabal al-Nusayriyah')) {
    return 'الحافة الانكسارية لجبل النصيرية (السلسلة الساحلية الغربية)';
  }
  if (landform.includes('Jabal Zawiya')) {
    return 'هضبة جبل الزاوية الكلسية الشرقية';
  }
  if (landform.includes('Alluvial Fan')) {
    return 'مروحة غرينية ومصطبة انتقالية عند أقدام الجبال';
  }
  if (landform.includes('Relict Marsh')) {
    return 'قاع مستنقعات الغاب التاريخية (أحواض طين الفيرتيسول)';
  }
  return 'قاع سهل الغاب الرسوبي الفيضي (أخدود العاصي)';
}

