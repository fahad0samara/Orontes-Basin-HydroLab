export function translateRiskClassAr(risk: 'Low' | 'Moderate' | 'High' | 'Critical'): string {
  switch (risk) {
    case 'Low':
      return 'منخفض';
    case 'Moderate':
      return 'متوسط';
    case 'High':
      return 'مرتفع';
    case 'Critical':
      return 'حرج جداً';
  }
}

